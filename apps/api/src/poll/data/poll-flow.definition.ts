export function getFlowNode(id: string): FlowNode {
  const node = POLL_FLOW_NODES[id];
  if (!node) {
    throw new Error(`Unknown poll flow node: ${id}`);
  }
  return node;
}

export function resolveNextNodeId(
  nodeId: string,
  answer: FlowAnswer
): string | null {
  const node = getFlowNode(nodeId);
  const edge = node.edges.find((e) => e.on === answer);
  return edge?.to ?? null;
}
